-- Створює місячні секції events від p_from_month на p_months_ahead місяців уперед.
-- Запускати щоночі: SELECT ensure_event_partitions();
CREATE OR REPLACE FUNCTION ensure_event_partitions(
    p_months_ahead integer DEFAULT NULL,
    p_from_month date DEFAULT date_trunc('month', statement_timestamp())::date
) RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    v_ahead   integer := COALESCE(p_months_ahead, get_param_int('event_partitions_months_ahead'), 3);
    v_start   date;
    v_name    text;
    v_created integer := 0;
BEGIN
    FOR i IN 0..v_ahead LOOP
        v_start := (date_trunc('month', p_from_month) + make_interval(months => i))::date;
        v_name  := format('events_%s', to_char(v_start, 'YYYY_MM'));
        IF to_regclass(v_name) IS NULL THEN
            EXECUTE format('CREATE TABLE %I PARTITION OF events FOR VALUES FROM (%L) TO (%L)',
                           v_name, v_start, (v_start + interval '1 month')::date);
            v_created := v_created + 1;
        END IF;
    END LOOP;
    RETURN v_created;
END;
$$;

-- Видаляє дані, старші за строки зберігання з platform_parameters.
-- Параметр = null -> об'єкт не очищується. Запускати щоночі: SELECT * FROM purge_expired_data();
CREATE OR REPLACE FUNCTION purge_expired_data()
RETURNS TABLE (object_name text, removed bigint)
LANGUAGE plpgsql AS $$
DECLARE
    v_months integer;
    v_cutoff timestamptz;
    v_part   record;
    v_count  bigint;
BEGIN
    -- events: видаляємо цілі секції (миттєво, без роздування таблиці)
    v_months := get_param_int('events_retention_months');
    IF v_months IS NOT NULL AND v_months > 0 THEN
        v_cutoff := date_trunc('month', statement_timestamp()) - make_interval(months => v_months);
        FOR v_part IN
            SELECT c.relname
            FROM pg_inherits i
            JOIN pg_class c ON c.oid = i.inhrelid
            WHERE i.inhparent = 'events'::regclass
              AND c.relname ~ '^events_[0-9]{4}_[0-9]{2}$'
              AND to_date(substr(c.relname, 8), 'YYYY_MM') + interval '1 month' <= v_cutoff
        LOOP
            EXECUTE format('DROP TABLE %I', v_part.relname);
            object_name := 'events: ' || v_part.relname; removed := NULL; RETURN NEXT;
        END LOOP;
        DELETE FROM events_default WHERE occurred_at < v_cutoff;
        GET DIAGNOSTICS v_count = ROW_COUNT;
        object_name := 'events_default'; removed := v_count; RETURN NEXT;
    END IF;

    v_months := get_param_int('email_log_retention_months');
    IF v_months IS NOT NULL AND v_months > 0 THEN
        DELETE FROM email_notifications
        WHERE created_at < statement_timestamp() - make_interval(months => v_months) AND status <> 'QUEUED';
        GET DIAGNOSTICS v_count = ROW_COUNT;
        object_name := 'email_notifications'; removed := v_count; RETURN NEXT;
    END IF;

    v_months := get_param_int('access_log_retention_months');
    IF v_months IS NOT NULL AND v_months > 0 THEN
        DELETE FROM data_access_log WHERE accessed_at < statement_timestamp() - make_interval(months => v_months);
        GET DIAGNOSTICS v_count = ROW_COUNT;
        object_name := 'data_access_log'; removed := v_count; RETURN NEXT;
    END IF;
END;
$$;


