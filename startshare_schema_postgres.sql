-- Перевіряє, що всі коди масиву існують у довіднику і не повторюються.
CREATE OR REPLACE FUNCTION assert_codes_exist(p_codes text[], p_ref regclass, p_label text) RETURNS void
LANGUAGE plpgsql STABLE AS $$
DECLARE bad text;
BEGIN
    IF p_codes IS NULL OR cardinality(p_codes) = 0 THEN
        RETURN;
    END IF;
    IF cardinality(p_codes) <> (SELECT count(DISTINCT c) FROM unnest(p_codes) c) THEN
        RAISE EXCEPTION '%: duplicate codes in %', p_label, p_codes USING ERRCODE = 'check_violation';
    END IF;
    EXECUTE format('SELECT c FROM unnest($1) c WHERE NOT EXISTS (SELECT 1 FROM %s r WHERE r.code = c) LIMIT 1', p_ref)
        INTO bad USING p_codes;
    IF bad IS NOT NULL THEN
        RAISE EXCEPTION '%: unknown code % (not in %)', p_label, bad, p_ref USING ERRCODE = 'foreign_key_violation';
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION check_mandate_codes() RETURNS trigger AS $$
BEGIN
    PERFORM assert_codes_exist(NEW.sector_codes::text[], 'sectors', 'mandates.sector_codes');
    PERFORM assert_codes_exist(NEW.stage_codes::text[], 'stages', 'mandates.stage_codes');
    PERFORM assert_codes_exist(NEW.country_codes::text[], 'countries', 'mandates.country_codes');
    PERFORM assert_codes_exist(NEW.region_codes::text[], 'regions', 'mandates.region_codes');
    PERFORM assert_codes_exist(NEW.business_model_codes::text[], 'business_models', 'mandates.business_model_codes');
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_mandates_codes
    BEFORE INSERT OR UPDATE ON mandates
    FOR EACH ROW EXECUTE FUNCTION check_mandate_codes();

-- Структура ризикових фраз у teaser_fields.risk_phrases (BA-AI-01).
CREATE OR REPLACE FUNCTION check_teaser_risk_phrases() RETURNS trigger AS $$
DECLARE e jsonb;
BEGIN
    FOR e IN SELECT * FROM jsonb_array_elements(NEW.risk_phrases) LOOP
        IF jsonb_typeof(e) <> 'object' THEN
            RAISE EXCEPTION 'teaser_fields.risk_phrases: element must be an object: %', e USING ERRCODE = 'check_violation';
        END IF;
        IF NOT EXISTS (SELECT 1 FROM risk_categories WHERE code = e->>'category') THEN
            RAISE EXCEPTION 'teaser_fields.risk_phrases: unknown category %', e->>'category' USING ERRCODE = 'foreign_key_violation';
        END IF;
        IF coalesce(e->>'source', '') NOT IN ('regex_pre', 'llm', 'regex_post') THEN
            RAISE EXCEPTION 'teaser_fields.risk_phrases: invalid source %', e->>'source' USING ERRCODE = 'check_violation';
        END IF;
        IF e->>'resolution' IS NOT NULL AND e->>'resolution' NOT IN ('removed', 'changed', 'kept') THEN
            RAISE EXCEPTION 'teaser_fields.risk_phrases: invalid resolution %', e->>'resolution' USING ERRCODE = 'check_violation';
        END IF;
        IF (e->>'resolution' IS NULL) <> (e->>'resolved_at' IS NULL) THEN
            RAISE EXCEPTION 'teaser_fields.risk_phrases: resolution and resolved_at must be set together' USING ERRCODE = 'check_violation';
        END IF;
    END LOOP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_teaser_fields_risk_phrases
    BEFORE INSERT OR UPDATE OF risk_phrases ON teaser_fields
    FOR EACH ROW EXECUTE FUNCTION check_teaser_risk_phrases();

-- Підписка відповідає тарифу: роль користувача = аудиторія тарифу;
-- платна підписка має кінець періоду, спосіб оплати й реквізити платника для рахунку;
-- безкоштовна — без способу оплати.
CREATE OR REPLACE FUNCTION check_subscription_plan() RETURNS trigger AS $$
DECLARE
    v_audience varchar; v_is_free boolean; v_role varchar;
BEGIN
    SELECT p.audience, p.is_free INTO v_audience, v_is_free FROM subscription_plans p WHERE p.id = NEW.plan_id;
    SELECT u.role INTO v_role FROM users u WHERE u.id = NEW.user_id;
    IF v_audience IS DISTINCT FROM v_role THEN
        RAISE EXCEPTION 'subscriptions: plan % is not for the role of user %', NEW.plan_id, NEW.user_id
            USING ERRCODE = 'check_violation';
    END IF;
    IF v_is_free THEN
        IF NEW.payment_method_code IS NOT NULL THEN
            RAISE EXCEPTION 'subscriptions: free plan % must not have a payment method', NEW.plan_id
                USING ERRCODE = 'check_violation';
        END IF;
    ELSIF NEW.current_period_end IS NULL OR NEW.payment_method_code IS NULL
          OR NEW.billing_name IS NULL OR NEW.billing_street IS NULL OR NEW.billing_postal_code IS NULL
          OR NEW.billing_city IS NULL OR NEW.billing_country_code IS NULL THEN
        RAISE EXCEPTION 'subscriptions: paid plan % requires period end, payment method and billing details', NEW.plan_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_subscriptions_plan
    BEFORE INSERT OR UPDATE ON subscriptions
    FOR EACH ROW EXECUTE FUNCTION check_subscription_plan();

