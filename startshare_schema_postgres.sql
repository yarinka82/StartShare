-- Попит і пропозиція за сегментами (поточний стан) | KPI: Задачі ClickUp «Що шукають інвестори» і «Що пропонують стартапи»
-- Гранулярність: Вимір × код значення (знімок на момент оновлення)
CREATE MATERIALIZED VIEW analytics.mv_market_segments AS
WITH live AS (
    SELECT sp.* FROM startup_profiles sp JOIN analytics.v_real_users u ON u.id = sp.user_id
    WHERE sp.status = 'LIVE' AND sp.moderation_hidden_at IS NULL),
active AS (
    SELECT m.* FROM mandates m
    JOIN investor_profiles ip ON ip.id = m.investor_profile_id AND ip.status_consent_id IS NOT NULL
    JOIN analytics.v_real_users u ON u.id = ip.user_id
    WHERE m.is_current),
seg AS (
    SELECT 'sector' AS dimension, s.code, s.name_de,
           (SELECT count(*) FROM live l WHERE l.sector_code = s.code) AS live_startups,
           (SELECT count(*) FROM active a WHERE s.code = ANY (a.sector_codes)) AS active_mandates
    FROM sectors s
    UNION ALL
    SELECT 'stage', s.code, s.name_de,
           (SELECT count(*) FROM live l WHERE l.stage_code = s.code),
           (SELECT count(*) FROM active a WHERE s.code = ANY (a.stage_codes))
    FROM stages s
    UNION ALL
    SELECT 'country', c.code, c.name_de,
           (SELECT count(*) FROM live l WHERE l.country_code = c.code),
           (SELECT count(*) FROM active a WHERE c.code = ANY (a.country_codes))
    FROM countries c
    UNION ALL
    SELECT 'region', r.code, r.name_de,
           (SELECT count(*) FROM live l WHERE l.region_code = r.code),
           -- мандати з цією землею + мандати з DE без земель (= уся Німеччина)
           (SELECT count(*) FROM active a WHERE r.code = ANY (a.region_codes)
                OR ('DE' = ANY (a.country_codes) AND cardinality(a.region_codes) = 0))
    FROM regions r
    UNION ALL
    SELECT 'business_model', b.code, b.name_de,
           (SELECT count(*) FROM live l WHERE l.business_model_code = b.code),
           (SELECT count(*) FROM active a WHERE b.code = ANY (a.business_model_codes))
    FROM business_models b)
SELECT dimension, code, name_de, live_startups, active_mandates,
       round(active_mandates::numeric / NULLIF(live_startups, 0), 2) AS mandates_per_startup
FROM seg;
CREATE UNIQUE INDEX uq_mv_market_segments ON analytics.mv_market_segments (dimension, code);
COMMENT ON MATERIALIZED VIEW analytics.mv_market_segments IS 'Попит і пропозиція за сегментами (поточний стан). Скільки LIVE-стартапів і чинних мандатів у кожному секторі, стадії, країні, землі, моделі бізнесу — де бракує стартапів, а де інвесторів.';

-- Розподіл сум раундів і чеків | KPI: «Що шукають інвестори» (розміри чеків) і «Що пропонують стартапи» (суми раундів)
-- Гранулярність: Ряд × діапазон суми
CREATE MATERIALIZED VIEW analytics.mv_amount_distribution AS
WITH amounts AS (
    SELECT 'startup_round' AS series, sp.round_amount_eur AS amount
    FROM startup_profiles sp JOIN analytics.v_real_users u ON u.id = sp.user_id
    WHERE sp.status = 'LIVE' AND sp.moderation_hidden_at IS NULL
    UNION ALL
    SELECT 'mandate_check_min', m.check_min_eur FROM mandates m
    JOIN investor_profiles ip ON ip.id = m.investor_profile_id JOIN analytics.v_real_users u ON u.id = ip.user_id
    WHERE m.is_current
    UNION ALL
    SELECT 'mandate_check_max', m.check_max_eur FROM mandates m
    JOIN investor_profiles ip ON ip.id = m.investor_profile_id JOIN analytics.v_real_users u ON u.id = ip.user_id
    WHERE m.is_current),
buckets(bucket_order, bucket_label, lo, hi) AS (VALUES
    (1, '< 100k', 0, 100000), (2, '100k – 250k', 100000, 250000), (3, '250k – 500k', 250000, 500000),
    (4, '500k – 1M', 500000, 1000000), (5, '1M – 2.5M', 1000000, 2500000), (6, '2.5M – 5M', 2500000, 5000000),
    (7, '≥ 5M', 5000000, NULL))
SELECT s.series, b.bucket_order::smallint AS bucket_order, b.bucket_label,
       count(a.amount) AS items
FROM (VALUES ('startup_round'), ('mandate_check_min'), ('mandate_check_max')) s(series)
CROSS JOIN buckets b
LEFT JOIN amounts a ON a.series = s.series AND a.amount >= b.lo AND (b.hi IS NULL OR a.amount < b.hi)
GROUP BY 1, 2, 3;
CREATE UNIQUE INDEX uq_mv_amount_distribution ON analytics.mv_amount_distribution (series, bucket_order);
COMMENT ON MATERIALIZED VIEW analytics.mv_amount_distribution IS 'Розподіл сум раундів і чеків. Чи збігаються суми, які шукають стартапи, з чеками, які готові дати інвестори.';

-- Довіра: скарги і пропозиції критеріїв | KPI: Довіра (скарги на 100 LIVE); довіра до пропозицій критеріїв
-- Гранулярність: Місяць
CREATE MATERIALIZED VIEW analytics.mv_trust_monthly AS
WITH months AS (
    SELECT generate_series(analytics.month_of(min(u.created_at)), analytics.month_of(statement_timestamp()),
                           interval '1 month')::date AS month
    FROM analytics.v_real_users u),
rep AS (
    SELECT analytics.month_of(r.created_at) AS month, count(*) AS reports,
           count(*) FILTER (WHERE r.decision IN ('profile_hidden', 'profile_removed')) AS hidden_removed,
           round((percentile_cont(0.5) WITHIN GROUP (ORDER BY extract(epoch FROM (r.decided_at - r.created_at))::numeric / 3600))::numeric, 1) AS med_hours
    FROM reports r JOIN analytics.v_real_users u ON u.id = r.reporter_user_id GROUP BY 1),
sug AS (
    SELECT analytics.month_of(cs.shown_at) AS month, count(*) AS shown, count(cs.accepted_at) AS accepted
    FROM criterion_suggestions cs JOIN investor_profiles ip ON ip.id = cs.investor_profile_id
    JOIN analytics.v_real_users u ON u.id = ip.user_id GROUP BY 1)
SELECT m.month,
       (SELECT count(*) FROM startup_profiles sp JOIN analytics.v_real_users u ON u.id = sp.user_id
        WHERE sp.went_live_at < m.month + interval '1 month'
          AND (sp.removed_at IS NULL OR sp.removed_at >= m.month)) AS live_profiles,
       coalesce(rep.reports, 0) AS reports,
       round(coalesce(rep.reports, 0) * 100.0 / NULLIF((SELECT count(*) FROM startup_profiles sp
             JOIN analytics.v_real_users u ON u.id = sp.user_id
             WHERE sp.went_live_at < m.month + interval '1 month'
               AND (sp.removed_at IS NULL OR sp.removed_at >= m.month)), 0), 2) AS reports_per_100_live,
       coalesce(rep.hidden_removed, 0) AS profiles_hidden_or_removed,
       rep.med_hours AS median_hours_to_decision,
       coalesce(sug.shown, 0) AS suggestions_shown,
       coalesce(sug.accepted, 0) AS suggestions_accepted,
       round(coalesce(sug.accepted, 0)::numeric / NULLIF(coalesce(sug.shown, 0), 0), 4) AS suggestion_acceptance_rate
FROM months m
LEFT JOIN rep ON rep.month = m.month
LEFT JOIN sug ON sug.month = m.month;
CREATE UNIQUE INDEX uq_mv_trust_monthly ON analytics.mv_trust_monthly (month);
COMMENT ON MATERIALIZED VIEW analytics.mv_trust_monthly IS 'Довіра: скарги і пропозиції критеріїв. Скільки скарг на 100 активних профілів і як інвестори приймають пропозиції змінити критерій.';

-- Відповіді на опитування | KPI: Цінність продукту (подія survey_answered в events)
