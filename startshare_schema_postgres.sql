-- Виправлення — окремим документом (сторно / кредит-нота, DB-16). Видалення заборонено.
CREATE OR REPLACE FUNCTION protect_invoice() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'subscription_payments: invoice % cannot be deleted', OLD.invoice_number
            USING ERRCODE = 'check_violation';
    END IF;
    IF (NEW.subscription_id, NEW.invoice_number, NEW.issued_at, NEW.period_start, NEW.period_end,
        NEW.amount_net_eur, NEW.vat_rate_pct, NEW.vat_amount_eur, NEW.amount_gross_eur, NEW.reverse_charge,
        NEW.buyer_name, NEW.buyer_street, NEW.buyer_postal_code, NEW.buyer_city, NEW.buyer_country_code, NEW.buyer_vat_id)
       IS DISTINCT FROM
       (OLD.subscription_id, OLD.invoice_number, OLD.issued_at, OLD.period_start, OLD.period_end,
        OLD.amount_net_eur, OLD.vat_rate_pct, OLD.vat_amount_eur, OLD.amount_gross_eur, OLD.reverse_charge,
