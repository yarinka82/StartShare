-- 02. legal_documents — Юридичні тексти (версії)
CREATE TABLE legal_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(8) NOT NULL,
    language VARCHAR(2) NOT NULL,
    version INTEGER NOT NULL,
    title VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    legal_approved_at TIMESTAMPTZ,
    valid_from TIMESTAMPTZ,
    valid_to TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT chk_legal_documents_code CHECK (code IN ('A', 'B', 'C', 'D', 'E', 'F', 'G', 'AGB', 'DSE')),
    CONSTRAINT chk_legal_documents_language CHECK (language IN ('de', 'en')),
    CONSTRAINT chk_legal_documents_version CHECK (version >= 1),
    CONSTRAINT chk_legal_documents_publish CHECK (valid_from IS NULL OR legal_approved_at IS NOT NULL),
    CONSTRAINT chk_legal_documents_period CHECK (valid_to IS NULL OR valid_to > valid_from),
    CONSTRAINT uq_legal_documents_version UNIQUE (code, language, version)
);
COMMENT ON TABLE legal_documents IS 'Юридичні тексти (версії). Зберігати всі юридичні тексти платформи (A–G, AGB, Datenschutzerklärung) з версіями та мовами, щоб завжди можна було довести, яку саме редакцію побачив або прийняв користувач.';
