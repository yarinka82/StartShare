COMMENT ON COLUMN legal_documents.code IS 'Код тексту. Який саме юридичний текст.';
COMMENT ON COLUMN legal_documents.language IS 'Мова. Мова редакції.';
COMMENT ON COLUMN legal_documents.version IS 'Версія. Порядковий номер редакції в межах коду й мови.';
