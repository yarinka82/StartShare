-- Підписки й дохід за місяцем | KPI: MRR, платні клієнти, відтік, фактичний дохід (монетизація)
-- Гранулярність: Місяць × аудиторія × код тарифу
CREATE MATERIALIZED VIEW analytics.mv_subscription_revenue_monthly AS
WITH months AS (
    SELECT generate_series(analytics.month_of(min(s.started_at)), analytics.month_of(statement_timestamp()),
                           interval '1 month')::date AS month
    FROM subscriptions s),
subs AS (
    SELECT s.*, p.code AS plan_code, p.audience, p.is_free,
           CASE WHEN p.billing_period = 'year' THEN p.price_net_eur / 12 ELSE p.price_net_eur END AS monthly_price
    FROM subscriptions s
    JOIN subscription_plans p ON p.id = s.plan_id
    JOIN analytics.v_real_users u ON u.id = s.user_id),
keys AS (SELECT DISTINCT audience, plan_code FROM subs),
grid AS (SELECT m.month, k.audience, k.plan_code,
                (m.month + interval '1 month')::timestamptz AS m_end, m.month::timestamptz AS m_start
         FROM months m CROSS JOIN keys k)
SELECT g.month, g.audience, g.plan_code,
       (SELECT count(*) FROM subs s WHERE s.audience = g.audience AND s.plan_code = g.plan_code AND s.is_free
          AND s.started_at < g.m_end AND (s.ended_at IS NULL OR s.ended_at >= g.m_end)) AS free_active_end,
       (SELECT count(*) FROM subs s WHERE s.audience = g.audience AND s.plan_code = g.plan_code AND NOT s.is_free
          AND s.started_at < g.m_end AND (s.ended_at IS NULL OR s.ended_at >= g.m_end)
          AND (s.trial_ends_at IS NULL OR s.trial_ends_at < g.m_end)) AS active_paid_end,
       (SELECT count(*) FROM subs s WHERE s.audience = g.audience AND s.plan_code = g.plan_code
          AND s.started_at < g.m_end AND (s.ended_at IS NULL OR s.ended_at >= g.m_end)
          AND s.trial_ends_at >= g.m_end) AS trialing_end,
       coalesce((SELECT sum(s.monthly_price) FROM subs s WHERE s.audience = g.audience AND s.plan_code = g.plan_code
          AND NOT s.is_free AND s.started_at < g.m_end AND (s.ended_at IS NULL OR s.ended_at >= g.m_end)
          AND (s.trial_ends_at IS NULL OR s.trial_ends_at < g.m_end)), 0)::numeric(12,2) AS mrr_eur,
       (SELECT count(*) FROM subs s WHERE s.audience = g.audience AND s.plan_code = g.plan_code
          AND s.started_at >= g.m_start AND s.started_at < g.m_end) AS new_subscriptions,
       (SELECT count(*) FROM subs s WHERE s.audience = g.audience AND s.plan_code = g.plan_code AND NOT s.is_free
          AND s.ended_at >= g.m_start AND s.ended_at < g.m_end AND s.end_reason <> 'plan_change') AS churned,
       round((SELECT count(*) FROM subs s WHERE s.audience = g.audience AND s.plan_code = g.plan_code AND NOT s.is_free AND s.ended_at >= g.m_start AND s.ended_at < g.m_end AND s.end_reason <> 'plan_change')::numeric / NULLIF((SELECT count(*) FROM subs s WHERE s.audience = g.audience AND s.plan_code = g.plan_code AND NOT s.is_free AND s.started_at < g.m_start AND (s.ended_at IS NULL OR s.ended_at >= g.m_start) AND (s.trial_ends_at IS NULL OR s.trial_ends_at < g.m_start)), 0), 4) AS churn_rate,
       coalesce((SELECT sum(pm.amount_net_eur) FROM subscription_payments pm JOIN subs s ON s.id = pm.subscription_id
          WHERE s.audience = g.audience AND s.plan_code = g.plan_code AND pm.status = 'PAID'
            AND pm.paid_at >= g.m_start AND pm.paid_at < g.m_end), 0) AS revenue_net_eur,
       coalesce((SELECT sum(pm.vat_amount_eur) FROM subscription_payments pm JOIN subs s ON s.id = pm.subscription_id
          WHERE s.audience = g.audience AND s.plan_code = g.plan_code AND pm.status = 'PAID'
            AND pm.paid_at >= g.m_start AND pm.paid_at < g.m_end), 0) AS vat_eur,
       (SELECT count(*) FROM subscription_payments pm JOIN subs s ON s.id = pm.subscription_id
          WHERE s.audience = g.audience AND s.plan_code = g.plan_code AND pm.status = 'FAILED'
            AND pm.issued_at >= g.m_start AND pm.issued_at < g.m_end) AS failed_payments
FROM grid g;
CREATE UNIQUE INDEX uq_mv_subscription_revenue_monthly ON analytics.mv_subscription_revenue_monthly (month, audience, plan_code);
COMMENT ON MATERIALIZED VIEW analytics.mv_subscription_revenue_monthly IS 'Підписки й дохід за місяцем. Скільки безкоштовних і платних підписок інвесторів і стартапів на кінець місяця, який MRR, скільки нових і завершених, який відтік платних і скільки грошей фактично отримано (нетто і ПДВ).';

-- Конверсія в платних клієнтів | KPI: Конверсія реєстрація → перша оплата (монетизація)
-- Гранулярність: Місяць реєстрації × роль
CREATE MATERIALIZED VIEW analytics.mv_paid_conversion_monthly AS
SELECT analytics.month_of(u.created_at) AS cohort_month, u.role,
       count(*) AS registered,
       count(*) FILTER (WHERE x.first_subscription IS NOT NULL) AS started_trial_or_paid,
       count(*) FILTER (WHERE x.first_payment IS NOT NULL) AS became_paid,
       round(count(*) FILTER (WHERE x.first_payment IS NOT NULL)::numeric / NULLIF(count(*), 0), 4) AS paid_conversion_rate,
       round((percentile_cont(0.5) WITHIN GROUP (ORDER BY extract(epoch FROM x.first_payment - u.created_at) / 86400))::numeric, 1)
           AS median_days_to_first_payment
FROM analytics.v_real_users u
LEFT JOIN LATERAL (
    SELECT min(s.started_at) AS first_subscription,
           min(pm.paid_at) FILTER (WHERE pm.status IN ('PAID', 'REFUNDED')) AS first_payment
    FROM subscriptions s
    JOIN subscription_plans p ON p.id = s.plan_id AND NOT p.is_free
    LEFT JOIN subscription_payments pm ON pm.subscription_id = s.id
    WHERE s.user_id = u.id) x ON TRUE
GROUP BY 1, 2;
CREATE UNIQUE INDEX uq_mv_paid_conversion_monthly ON analytics.mv_paid_conversion_monthly (cohort_month, role);
COMMENT ON MATERIALIZED VIEW analytics.mv_paid_conversion_monthly IS 'Конверсія в платних клієнтів. Яка частка зареєстрованих інвесторів і стартапів з кожної місячної когорти стала платними клієнтами і як швидко.';

-- Перехід з безкоштовної фази на платну | KPI: free_to_paid_rate (монетизація, рішення PM 05.10.2026)
-- Гранулярність: Місяць завершення безкоштовної підписки × аудиторія
CREATE MATERIALIZED VIEW analytics.mv_free_to_paid_conversion AS
WITH f AS (
    SELECT s.user_id, p.audience, s.ended_at, s.end_reason, s.started_at
    FROM subscriptions s
    JOIN subscription_plans p ON p.id = s.plan_id AND p.is_free
    JOIN analytics.v_real_users u ON u.id = s.user_id
    WHERE s.status = 'ENDED' AND s.end_reason <> 'account_deleted'),
x AS (
    SELECT f.*, nxt.paid_started_at, nxt.has_payment
    FROM f
    LEFT JOIN LATERAL (
        SELECT min(s2.started_at) AS paid_started_at,
               bool_or(EXISTS (SELECT 1 FROM subscription_payments pm
                               WHERE pm.subscription_id = s2.id AND pm.status IN ('PAID', 'REFUNDED'))) AS has_payment
        FROM subscriptions s2 JOIN subscription_plans p2 ON p2.id = s2.plan_id AND NOT p2.is_free
        WHERE s2.user_id = f.user_id AND s2.started_at >= f.started_at) nxt ON TRUE)
SELECT analytics.month_of(x.ended_at) AS month, x.audience,
       count(*) AS free_ended,
       count(*) FILTER (WHERE x.end_reason = 'free_period_ended') AS ended_by_phase_end,
       count(*) FILTER (WHERE x.end_reason = 'plan_change') AS switched_early,
       count(*) FILTER (WHERE x.paid_started_at IS NOT NULL) AS converted_to_paid,
       count(*) FILTER (WHERE x.has_payment) AS converted_and_paid,
       round(count(*) FILTER (WHERE x.has_payment)::numeric / NULLIF(count(*), 0), 4) AS free_to_paid_rate,
       round((percentile_cont(0.5) WITHIN GROUP (ORDER BY greatest(extract(epoch FROM x.paid_started_at - x.ended_at), 0) / 86400))::numeric, 1)
           AS median_days_to_paid
FROM x
GROUP BY 1, 2;
CREATE UNIQUE INDEX uq_mv_free_to_paid_conversion ON analytics.mv_free_to_paid_conversion (month, audience);
COMMENT ON MATERIALIZED VIEW analytics.mv_free_to_paid_conversion IS 'Перехід з безкоштовної фази на платну. Скільки користувачів з безкоштовним доступом стартової фази оформили платний тариф і скільки з них реально оплатили — головний показник успіху переходу на платну модель.';

-- Способи оплати й рахунки за місяцем | KPI: Частка способів оплати, payment_failure_rate, reverse charge (монетизація)
-- Гранулярність: Місяць рахунку × спосіб оплати
CREATE MATERIALIZED VIEW analytics.mv_payment_methods_monthly AS
SELECT analytics.month_of(pm.issued_at) AS month, coalesce(pm.payment_method_code, 'none') AS payment_method_code,
       count(*) AS invoices,
       count(*) FILTER (WHERE pm.status = 'PAID') AS paid,
       count(*) FILTER (WHERE pm.status = 'FAILED') AS failed,
       count(*) FILTER (WHERE pm.status = 'REFUNDED') AS refunded,
       round(count(*) FILTER (WHERE pm.status = 'FAILED')::numeric / NULLIF(count(*) FILTER (WHERE pm.status IN ('PAID', 'FAILED', 'REFUNDED')), 0), 4) AS payment_failure_rate,
       count(*) FILTER (WHERE pm.reverse_charge) AS reverse_charge_invoices,
       coalesce(sum(pm.amount_net_eur) FILTER (WHERE pm.status IN ('PAID', 'REFUNDED')), 0) AS net_eur,
       coalesce(sum(pm.amount_gross_eur) FILTER (WHERE pm.status IN ('PAID', 'REFUNDED')), 0) AS gross_eur
FROM subscription_payments pm
JOIN subscriptions s ON s.id = pm.subscription_id
JOIN analytics.v_real_users u ON u.id = s.user_id
GROUP BY 1, 2;
CREATE UNIQUE INDEX uq_mv_payment_methods_monthly ON analytics.mv_payment_methods_monthly (month, payment_method_code);
COMMENT ON MATERIALIZED VIEW analytics.mv_payment_methods_monthly IS 'Способи оплати й рахунки за місяцем. Якими способами платять (PayPal, Apple Pay, SEPA тощо), де найбільше невдалих оплат, скільки рахунків з reverse charge — для вибору способів оплати, які варто підтримувати.';

-- Щоденний знімок ключових лічильників: дає історію росту, якої немає в MV (вони показують поточний стан).
CREATE TABLE analytics.daily_platform_snapshot (
    snapshot_date DATE PRIMARY KEY,
    startups_registered INTEGER NOT NULL,
    startups_live INTEGER NOT NULL,
    startups_paused INTEGER NOT NULL,
    startups_draft INTEGER NOT NULL,
    investors_registered INTEGER NOT NULL,
    investors_with_mandate INTEGER NOT NULL,
    open_requests INTEGER NOT NULL,
    introductions_total INTEGER NOT NULL,
    free_access_users INTEGER NOT NULL,
    paid_investors INTEGER NOT NULL,
    paid_startups INTEGER NOT NULL,
    mrr_eur NUMERIC(12,2) NOT NULL,
    taken_at TIMESTAMPTZ NOT NULL
);
COMMENT ON TABLE analytics.daily_platform_snapshot IS 'Щоденні лічильники платформи для графіків росту. Заповнює analytics.take_daily_snapshot().';

CREATE OR REPLACE FUNCTION analytics.take_daily_snapshot() RETURNS date
LANGUAGE sql AS $$
    INSERT INTO analytics.daily_platform_snapshot AS s
    SELECT (statement_timestamp() AT TIME ZONE 'Europe/Berlin')::date,
           count(*) FILTER (WHERE u.role = 'startup'),
           count(*) FILTER (WHERE sp.status = 'LIVE' AND sp.moderation_hidden_at IS NULL),
           count(*) FILTER (WHERE sp.status = 'PAUSED'),
           count(*) FILTER (WHERE sp.status = 'DRAFT'),
           count(*) FILTER (WHERE u.role = 'investor'),
           count(*) FILTER (WHERE ip.status_consent_id IS NOT NULL
                            AND EXISTS (SELECT 1 FROM public.mandates m WHERE m.investor_profile_id = ip.id AND m.is_current)),
           (SELECT count(*) FROM public.introductions WHERE status = 'INTERESTED'),
           (SELECT count(*) FROM public.introductions WHERE status = 'INTRODUCED'),
           (SELECT count(*) FROM public.subscriptions s JOIN public.subscription_plans p ON p.id = s.plan_id
             JOIN analytics.v_real_users ru ON ru.id = s.user_id
             WHERE s.status = 'ACTIVE' AND p.is_free),
           (SELECT count(*) FROM public.subscriptions s JOIN public.subscription_plans p ON p.id = s.plan_id
             JOIN analytics.v_real_users ru ON ru.id = s.user_id
             WHERE s.status IN ('ACTIVE', 'PAST_DUE') AND NOT p.is_free AND p.audience = 'investor'),
           (SELECT count(*) FROM public.subscriptions s JOIN public.subscription_plans p ON p.id = s.plan_id
             JOIN analytics.v_real_users ru ON ru.id = s.user_id
             WHERE s.status IN ('ACTIVE', 'PAST_DUE') AND NOT p.is_free AND p.audience = 'startup'),
           coalesce((SELECT sum(CASE WHEN p.billing_period = 'year' THEN p.price_net_eur / 12 ELSE p.price_net_eur END)
             FROM public.subscriptions s JOIN public.subscription_plans p ON p.id = s.plan_id
             JOIN analytics.v_real_users ru ON ru.id = s.user_id
             WHERE s.status IN ('ACTIVE', 'PAST_DUE') AND NOT p.is_free), 0),
           statement_timestamp()
    FROM analytics.v_real_users u
    LEFT JOIN public.startup_profiles sp ON sp.user_id = u.id
    LEFT JOIN public.investor_profiles ip ON ip.user_id = u.id
    ON CONFLICT (snapshot_date) DO UPDATE SET
        startups_registered = EXCLUDED.startups_registered, startups_live = EXCLUDED.startups_live,
        startups_paused = EXCLUDED.startups_paused, startups_draft = EXCLUDED.startups_draft,
        investors_registered = EXCLUDED.investors_registered, investors_with_mandate = EXCLUDED.investors_with_mandate,
        open_requests = EXCLUDED.open_requests, introductions_total = EXCLUDED.introductions_total,
        free_access_users = EXCLUDED.free_access_users, paid_investors = EXCLUDED.paid_investors, paid_startups = EXCLUDED.paid_startups, mrr_eur = EXCLUDED.mrr_eur,
        taken_at = EXCLUDED.taken_at
    RETURNING s.snapshot_date;
$$;

-- Оновлює всі MV схеми analytics. CONCURRENTLY: дашборди читають старі дані, поки рахуються нові.
CREATE OR REPLACE FUNCTION analytics.refresh_all() RETURNS TABLE (view_name text, seconds numeric)
LANGUAGE plpgsql AS $$
DECLARE
    v record;
    t0 timestamptz;
BEGIN
    FOR v IN SELECT matviewname FROM pg_matviews WHERE schemaname = 'analytics' ORDER BY matviewname LOOP
        t0 := clock_timestamp();
        EXECUTE format('REFRESH MATERIALIZED VIEW CONCURRENTLY analytics.%I', v.matviewname);
        view_name := v.matviewname;
        seconds := round(extract(epoch FROM clock_timestamp() - t0)::numeric, 3);
        RETURN NEXT;
    END LOOP;
END;
$$;

