-- Автооновлення updated_at при будь-якому UPDATE (на випадок змін в обхід Django ORM).
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


