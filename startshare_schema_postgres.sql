-- Секція за замовчуванням: подія з датою поза створеними секціями не втрачається.
CREATE TABLE events_default PARTITION OF events DEFAULT;

-- Значення цілочисельного параметра з platform_parameters; JSON null або відсутній ключ -> NULL.
CREATE OR REPLACE FUNCTION get_param_int(p_key text) RETURNS integer
