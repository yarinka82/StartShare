-- Реальні користувачі платформи: без тестових акаунтів і співробітників.
CREATE OR REPLACE VIEW analytics.v_real_users AS
SELECT id, role, created_at, deleted_at FROM public.users
WHERE NOT is_test AND role IN ('startup', 'investor');

-- Воронка стартапів за тижнем реєстрації | KPI: Активація стартапів; воронка стартапу (BA-TP)
-- Гранулярність: Тиждень реєстрації (когорта)
CREATE MATERIALIZED VIEW analytics.mv_startup_funnel_weekly AS
SELECT analytics.week_of(u.created_at) AS cohort_week,
       count(*) AS registered,
       count(*) FILTER (WHERE d.first_upload IS NOT NULL) AS deck_uploaded,
       count(*) FILTER (WHERE j.first_draft IS NOT NULL) AS ai_draft_ready,
       count(*) FILTER (WHERE t.first_approved IS NOT NULL) AS teaser_approved,
       count(*) FILTER (WHERE sp.went_live_at IS NOT NULL) AS went_live,
       count(*) FILTER (WHERE sp.removed_by = 'system') AS drafts_auto_removed,
       round(count(*) FILTER (WHERE sp.went_live_at IS NOT NULL)::numeric / NULLIF(count(*), 0), 4) AS activation_rate,
       round((percentile_cont(0.5) WITHIN GROUP (ORDER BY extract(epoch FROM (sp.went_live_at - u.created_at))::numeric / 3600))::numeric, 1) AS median_hours_to_live
FROM startup_profiles sp
JOIN analytics.v_real_users u ON u.id = sp.user_id
LEFT JOIN LATERAL (SELECT min(p.uploaded_at) AS first_upload FROM pitch_decks p
                   WHERE p.startup_profile_id = sp.id) d ON TRUE
LEFT JOIN LATERAL (SELECT min(p.processing_finished_at) AS first_draft FROM pitch_decks p
                   WHERE p.startup_profile_id = sp.id AND p.processing_state = 'DRAFT_READY') j ON TRUE
LEFT JOIN LATERAL (SELECT min(t.approved_at) AS first_approved FROM teasers t
                   WHERE t.startup_profile_id = sp.id) t ON TRUE
GROUP BY 1;
CREATE UNIQUE INDEX uq_mv_startup_funnel_weekly ON analytics.mv_startup_funnel_weekly (cohort_week);
COMMENT ON MATERIALIZED VIEW analytics.mv_startup_funnel_weekly IS 'Воронка стартапів за тижнем реєстрації. Скільки стартапів з кожної когорти реєстрації дійшли до кожного кроку: дек → чернетка ШІ → затвердження → LIVE.';

