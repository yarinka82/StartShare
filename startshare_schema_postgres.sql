-- 28. subscription_payments — Рахунки й оплати (Rechnungen)
CREATE TABLE subscription_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL REFERENCES subscriptions (id) DEFERRABLE INITIALLY DEFERRED,
    invoice_number VARCHAR(30) NOT NULL UNIQUE,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    period_start TIMESTAMPTZ NOT NULL,
    period_end TIMESTAMPTZ NOT NULL,
    amount_net_eur NUMERIC(10,2) NOT NULL,
    vat_rate_pct NUMERIC(5,2) NOT NULL,
    vat_amount_eur NUMERIC(10,2) NOT NULL,
    amount_gross_eur NUMERIC(10,2) NOT NULL,
    reverse_charge BOOLEAN NOT NULL DEFAULT FALSE,
    buyer_name VARCHAR(200) NOT NULL,
    buyer_street VARCHAR(200) NOT NULL,
    buyer_postal_code VARCHAR(16) NOT NULL,
    buyer_city VARCHAR(100) NOT NULL,
    buyer_country_code VARCHAR(2) NOT NULL REFERENCES countries (code) DEFERRABLE INITIALLY DEFERRED,
    buyer_vat_id VARCHAR(20),
    payment_method_code VARCHAR(32) REFERENCES payment_methods (code) DEFERRABLE INITIALLY DEFERRED,
    status VARCHAR(10) NOT NULL DEFAULT 'OPEN',
    paid_at TIMESTAMPTZ,
    refunded_at TIMESTAMPTZ,
    failure_code VARCHAR(100),
    provider_invoice_id VARCHAR(100),
    provider_payment_id VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT uq_subscription_payments_period UNIQUE (subscription_id, period_start),
    CONSTRAINT uq_subscription_payments_invoice UNIQUE (provider_invoice_id),
    CONSTRAINT chk_subscription_payments_number CHECK (length(btrim(invoice_number)) > 0),
    CONSTRAINT chk_subscription_payments_period CHECK (period_end > period_start),
    CONSTRAINT chk_subscription_payments_amounts CHECK (amount_net_eur >= 0 AND vat_rate_pct >= 0 AND vat_rate_pct < 100 AND vat_amount_eur = round(amount_net_eur * vat_rate_pct / 100, 2) AND amount_gross_eur = amount_net_eur + vat_amount_eur),
    CONSTRAINT chk_subscription_payments_reverse_charge CHECK ((reverse_charge AND vat_rate_pct = 0 AND buyer_vat_id IS NOT NULL AND buyer_country_code <> 'DE') OR (NOT reverse_charge AND vat_rate_pct > 0)),
    CONSTRAINT chk_subscription_payments_status CHECK (status IN ('OPEN', 'PAID', 'FAILED', 'REFUNDED', 'VOID')),
